CREATE TABLE organization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    logo_url VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_organization PRIMARY KEY (id)
);

CREATE TABLE organization_unit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    organization_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    city VARCHAR(255) NOT NULL,
    state VARCHAR(255) NOT NULL,
    country VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    contact_phone VARCHAR(255) NOT NULL,
    contact_email VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL,
    join_code VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_organization_unit PRIMARY KEY (id),
    CONSTRAINT uk_organization_unit_join_code UNIQUE (join_code),
    CONSTRAINT fk_organization_unit_organization
        FOREIGN KEY (organization_id) REFERENCES organization (id)
);

CREATE INDEX idx_organization_unit_organization_id
    ON organization_unit (organization_id);
