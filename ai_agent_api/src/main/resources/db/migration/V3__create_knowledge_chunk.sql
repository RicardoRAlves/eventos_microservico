
CREATE TABLE knowledge_chunk (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 knowledge_document_id BIGINT NOT NULL,

                                 chunk_index INTEGER NOT NULL,

                                 content TEXT NOT NULL,

                                 embedding VECTOR(768),

                                 created_at TIMESTAMP WITH TIME ZONE NOT NULL
                                     DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT fk_knowledge_chunk_document
                                     FOREIGN KEY (knowledge_document_id)
                                         REFERENCES knowledge_document(id)
                                         ON DELETE CASCADE,

                                 CONSTRAINT uk_knowledge_chunk_document_index
                                     UNIQUE (knowledge_document_id, chunk_index),

                                 CONSTRAINT ck_knowledge_chunk_index
                                     CHECK (chunk_index >= 0)
);

CREATE INDEX idx_knowledge_chunk_document
    ON knowledge_chunk(knowledge_document_id);
